def cost_units(project, sheets):
    """Deterministic price of a generation, in whatever units the caller meters."""
    return 20 + 6 * len(sheets) + 2 * len(project.massing.levels)


def manifest(project, sheets, spec=None, model=None):
    """Everything the calling platform needs to persist and display."""
    m = project.massing
    levels = []
    for i, lv in enumerate(m.levels):
        fp = project.floorplans[i]
        rooms = [{"code": r.code, "name": r.name, "category": r.cat,
                  "area_m2": round(r.area, 1), "daylit": r.daylit}
                 for r in fp.rooms]
        levels.append({
            "index": i, "name": lv.name, "ffl_m": round(lv.ffl, 3),
            "floor_to_floor_m": round(lv.to_ffl, 3),
            "area_m2": round(lv.area, 1),
            "circulation_m2": round(fp.circulation_area, 1),
            "room_count": len(fp.rooms), "corridors": len(fp.circulation),
            "daylit_m2": round(sum(r.area for r in fp.rooms if r.daylit), 1),
            "internal_m2": round(sum(r.area for r in fp.rooms if not r.daylit), 1),
            "rooms": rooms,
        })
    foot = m.footprint()
    out = {
        "engine": {"name": "archiai", "version": ENGINE_VERSION},
        "project": {
            "name": project.info.get("name"),
            "number": project.info.get("number"),
            "typology": m.name,
            "storeys": len(m.levels),
            "gia_m2": round(m.gia(), 1),
            "footprint_m2": round(foot.area, 1),
            "height_m": round(m.height, 3),
            "bbox_m": [round(v, 3) for v in foot.bbox()],
        },
        "levels": levels,
        "sheets": sheets,
        "totals": {
            "rooms": sum(len(f.rooms) for f in project.floorplans),
            "sheets": len(sheets),
            "cost_units": cost_units(project, sheets),
        },
    }
    source = getattr(project, "source", None)
    if source:
        out["source"] = source
        out["project"]["revision"] = source.get("revision", "P01")
    if spec is not None:
        out["spec"] = {
            "use": spec.use, "shape": spec.shape, "storeys": spec.storeys,
            "area_m2": spec.area, "entrance_azimuth": spec.entrance,
            "floor_to_floor_m": spec.floor_to_floor, "name": spec.name,
        }
        out["assumptions"] = list(spec.assumptions)
    if model:
        out["model"] = model
    return out
