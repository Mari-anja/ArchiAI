def _sub(a, b):
    return (a[0] - b[0], a[1] - b[1], a[2] - b[2])


def _add(a, b):
    return (a[0] + b[0], a[1] + b[1], a[2] + b[2])


def _mul(a, k):
    return (a[0] * k, a[1] * k, a[2] * k)


def _dot(a, b):
    return a[0] * b[0] + a[1] * b[1] + a[2] * b[2]


def _cross(a, b):
    return (a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2],
            a[0] * b[1] - a[1] * b[0])


def _norm(a):
    m = math.sqrt(_dot(a, a)) or 1.0
    return (a[0] / m, a[1] / m, a[2] / m)


def _newell(pts):
    nx = ny = nz = 0.0
    m = len(pts)
    for i in range(m):
        a, b = pts[i], pts[(i + 1) % m]
        nx += (a[1] - b[1]) * (a[2] + b[2])
        ny += (a[2] - b[2]) * (a[0] + b[0])
        nz += (a[0] - b[0]) * (a[1] + b[1])
    return (nx, ny, nz)


class Camera:
    """Perspective or parallel, looking from `eye` at `target`.

    Everything is done in camera space so the near plane can be clipped
    properly: a face with one corner behind the lens has to be cut, not
    dropped, or a wall vanishes the moment you step close to it."""

    NEAR = 0.35

    def __init__(self, eye, target, fov=48.0, parallel=False, span=None,
                 roll=0.0, width=1600, height=1000):
        self.eye = tuple(float(c) for c in eye)
        self.target = tuple(float(c) for c in target)
        f = _norm(_sub(self.target, self.eye))
        up = (0.0, 0.0, 1.0)
        if abs(_dot(f, up)) > 0.999:
            up = (0.0, 1.0, 0.0)
        r = _norm(_cross(f, up))
        u = _cross(r, f)
        if roll:
            a = math.radians(roll)
            r, u = (_add(_mul(r, math.cos(a)), _mul(u, math.sin(a))),
                    _add(_mul(u, math.cos(a)), _mul(r, -math.sin(a))))
        self.f, self.r, self.u = f, r, u
        self.parallel = parallel
        self.width, self.height = float(width), float(height)
        self.aspect = self.width / self.height
        self.span = span or 60.0
        self.k = (self.height / 2.0) / math.tan(math.radians(fov) / 2.0)
        self.fov = fov

    def to_cam(self, p):
        d = _sub(p, self.eye)
        return (_dot(d, self.r), _dot(d, self.u), _dot(d, self.f))

    def project(self, c):
        """Camera space to pixels. z must already be in front of the lens."""
        if self.parallel:
            s = self.height / self.span
            return (self.width / 2.0 + c[0] * s, self.height / 2.0 - c[1] * s)
        s = self.k / max(c[2], 1e-6)
        return (self.width / 2.0 + c[0] * s, self.height / 2.0 - c[1] * s)

    def clip(self, pts):
        """Sutherland-Hodgman against the near plane, in camera space."""
        if self.parallel:
            return pts
        out = []
        n = len(pts)
        for i in range(n):
            a, b = pts[i], pts[(i + 1) % n]
            ina, inb = a[2] >= self.NEAR, b[2] >= self.NEAR
            if ina:
                out.append(a)
            if ina != inb:
                t = (self.NEAR - a[2]) / (b[2] - a[2])
                out.append((a[0] + (b[0] - a[0]) * t,
                            a[1] + (b[1] - a[1]) * t, self.NEAR))
        return out


