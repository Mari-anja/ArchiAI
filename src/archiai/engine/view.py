"""Views of the building: pick a camera, pick what to include, get a picture.

This is the deterministic half of rendering. Nothing here is generated by a
model; the picture is the building, drawn with a real camera, a real sun and
the same facade rules the elevations and the window schedule use. Ask for the
same view twice and you get the same image, which is what makes it useful as
a base for a photoreal pass later on.

World axes are the model's: x east, y north, z up.
"""

