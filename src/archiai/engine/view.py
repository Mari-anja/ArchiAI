def _radius(project):
    x0, y0, x1, y1 = project.massing.footprint().bbox()
    return max(x1 - x0, y1 - y0) / 2.0


def _wobble(i, salt=0):
    """A repeatable number in 0..1 from an index, so context never changes
    between two renders of the same building."""
    v = (i * 2654435761 + salt * 40503 + 12345) & 0xFFFFFFFF
    v ^= (v >> 13)
    v = (v * 1274126177) & 0xFFFFFFFF
    return ((v >> 8) & 0xFFFF) / 65535.0


def _site(project):
    """Centre, bbox and half-extents of the plate the building sits on."""
    plate = project.massing.footprint()
    x0, y0, x1, y1 = plate.bbox()
    return plate, ((x0 + x1) / 2.0, (y0 + y1) / 2.0), (x0, y0, x1, y1)


def _reach(project, azimuth_deg):
    """How far the building sticks out in one direction, from its centre."""
    plate, (cx, cy), _bb = _site(project)
    a = math.radians(azimuth_deg)
    dx, dy = math.cos(a), math.sin(a)
    return max((p[0] - cx) * dx + (p[1] - cy) * dy for p in plate.outer)


def _pad(project):
    """The paved apron around the building; everything outside stands beyond it."""
    return max(_radius(project) * 0.32, 8.0)


def _ring_points(project, count, offset, phase=0.0, salt=0):
    """Positions spaced around the site, following its shape rather than a
    circle, so a long building does not get its trees bunched at the ends."""
    plate, (cx, cy), (x0, y0, x1, y1) = _site(project)
    hx, hy = (x1 - x0) / 2.0 + offset, (y1 - y0) / 2.0 + offset
    per = 2 * (hx + hy) * 2
    out = []
    for i in range(count):
        t = ((i + phase) / count + 0.02 * _wobble(i, salt)) % 1.0
        s = t * per
        if s < 2 * hx:
            p = (cx - hx + s, cy - hy)
        elif s < 2 * hx + 2 * hy:
            p = (cx + hx, cy - hy + (s - 2 * hx))
        elif s < 4 * hx + 2 * hy:
            p = (cx + hx - (s - 2 * hx - 2 * hy), cy + hy)
        else:
            p = (cx - hx, cy + hy - (s - 4 * hx - 2 * hy))
        if plate.contains(p):
            continue
        out.append(p)
    return out


def ground(scene, project, size=None):
    """The ground, drawn far enough out that its edge is never in frame."""
    cam = scene.cam
    cx, cy = G.centroid(project.massing.footprint().outer)
    reach = math.hypot(cam.eye[0] - cx, cam.eye[1] - cy) + cam.eye[2]
    r = size or max(_radius(project) * 8.0, reach * 14.0)
    scene.face([(cx - r, cy - r, 0.0), (cx + r, cy - r, 0.0),
                (cx + r, cy + r, 0.0), (cx - r, cy + r, 0.0)],
               "ground", cull=False, layer=-3)
    x0, y0, x1, y1 = project.massing.footprint().bbox()
    pad = max(_radius(project) * 0.32, 8.0)
    scene.face([(x0 - pad, y0 - pad, 0.002), (x1 + pad, y0 - pad, 0.002),
                (x1 + pad, y1 + pad, 0.002), (x0 - pad, y1 + pad, 0.002)],
               "paving", cull=False, layer=-3)


def context(scene, project, count=14, seed=0):
    """Neighbouring blocks, placed once and always the same."""
    m = project.massing
    plate, (cx, cy), _bb = _site(project)
    r = _radius(project)
    pad = _pad(project)
    # neighbours sit across a street, and they are neighbours: they read as
    # the setting, so they stay below the building they are the setting for
    street = max(pad * 2.2, m.height * 0.8, 16.0)
    block = max(r * 0.34, 9.0)
    for i, (px, py) in enumerate(_ring_points(project, count,
                                              street + block, 0.5, seed)):
        a = math.atan2(py - cy, px - cx)
        push = block * (0.5 + 1.4 * _wobble(i, seed))
        px, py = px + math.cos(a) * push, py + math.sin(a) * push
        w = block * (0.7 + 0.8 * _wobble(i, seed + 1))
        h = block * (0.6 + 0.8 * _wobble(i, seed + 2))
        z = max(5.0, min(m.height * 0.85,
                         m.height * (0.28 + 0.46 * _wobble(i, seed + 3))))
        ca, sa = math.cos(a), math.sin(a)
        corners = [(-w, -h), (w, -h), (w, h), (-w, h)]
        base = [(px + x * ca - y * sa, py + x * sa + y * ca) for (x, y) in corners]
        if any(plate.contains(p) for p in base):
            continue
        for k in range(4):
            p0, p1 = base[k], base[(k + 1) % 4]
            scene.face([(p0[0], p0[1], 0.0), (p1[0], p1[1], 0.0),
                        (p1[0], p1[1], z), (p0[0], p0[1], z)], "context")
        scene.face([(p[0], p[1], z) for p in base], "context")


def trees(scene, project, count=12, seed=1):
    pad = _pad(project)
    for i, (px, py) in enumerate(_ring_points(project, count, pad * 0.72,
                                              0.35, seed)):
        h = 5.0 + 3.5 * _wobble(i, seed + 6)
        tr = 0.16
        for k in range(4):
            b0 = 2 * math.pi * k / 4
            b1 = 2 * math.pi * (k + 1) / 4
            scene.face([(px + tr * math.cos(b0), py + tr * math.sin(b0), 0.0),
                        (px + tr * math.cos(b1), py + tr * math.sin(b1), 0.0),
                        (px + tr * math.cos(b1), py + tr * math.sin(b1), h * 0.45),
                        (px + tr * math.cos(b0), py + tr * math.sin(b0), h * 0.45)],
                       "trunk", cull=False)
        crown = [(h * 0.10, h * 0.40), (h * 0.28, h * 0.55),
                 (h * 0.30, h * 0.70), (h * 0.20, h * 0.87), (0.0, h)]
        prev = None
        for (rad, z) in crown:
            ring = [(px + rad * math.cos(2 * math.pi * k / 7),
                     py + rad * math.sin(2 * math.pi * k / 7), z) for k in range(7)]
            if prev:
                for k in range(7):
                    scene.face([prev[k], prev[(k + 1) % 7], ring[(k + 1) % 7],
                                ring[k]], "tree", cull=False)
            prev = ring


def cars(scene, project, count=6, seed=2):
    plate, (cx, cy), _bb = _site(project)
    pad = _pad(project)
    for i, (px, py) in enumerate(_ring_points(project, count, pad * 1.06,
                                              0.7, seed)):
        a = math.atan2(py - cy, px - cx)
        ca, sa = math.cos(a + math.pi / 2), math.sin(a + math.pi / 2)
        L, W = 2.30, 0.90
        base = [(px + x * ca - y * sa, py + x * sa + y * ca)
                for (x, y) in ((-L, -W), (L, -W), (L, W), (-L, W))]
        for (z0, z1, inset) in ((0.20, 0.80, 0.0), (0.80, 1.42, 0.35)):
            ring = base
            if inset:
                ring = [(px + (p[0] - px) * (1 - inset), py + (p[1] - py) * (1 - inset))
                        for p in base]
            for k in range(4):
                p0, p1 = ring[k], ring[(k + 1) % 4]
                scene.face([(p0[0], p0[1], z0), (p1[0], p1[1], z0),
                            (p1[0], p1[1], z1), (p0[0], p0[1], z1)], "car")
            scene.face([(p[0], p[1], z1) for p in ring], "car")


def people(scene, project, count=9, seed=4):
    """Figures placed on the ground, drawn facing the camera."""
    cam = scene.cam
    plate, (cx, cy), _bb = _site(project)
    pad = _pad(project)
    az = project.brief.entrance_azimuth
    for i in range(count):
        a = math.radians(az + (_wobble(i, seed) - 0.5) * 150.0)
        d = _reach(project, math.degrees(a)) + pad * (0.20 + 0.62 * _wobble(i, seed + 7))
        px, py = cx + math.cos(a) * d, cy + math.sin(a) * d
        if plate.contains((px, py)):
            continue
        h = 1.62 + 0.16 * _wobble(i, seed + 8)
        foot, head = cam.to_cam((px, py, 0.0)), cam.to_cam((px, py, h))
        if min(foot[2], head[2]) < cam.NEAR:
            continue
        f2, h2 = cam.project(foot), cam.project(head)
        ph = f2[1] - h2[1]
        if ph < 3.0 or ph > cam.height * 1.4:
            continue
        w = ph * 0.20
        sh = h2[1] + ph * 0.17                      # shoulder line
        body = [(f2[0] - w * 0.30, f2[1]),
                (f2[0] - w * 0.16, f2[1] - ph * 0.42),
                (f2[0] - w * 0.50, sh + ph * 0.06),
                (f2[0] - w * 0.34, sh),
                (f2[0] + w * 0.34, sh),
                (f2[0] + w * 0.50, sh + ph * 0.06),
                (f2[0] + w * 0.16, f2[1] - ph * 0.42),
                (f2[0] + w * 0.30, f2[1])]
        facing = _mul(cam.f, -1.0)
        fill = scene.paint(facing, "person", cam.f, foot[2], flat="#4b5058")
        scene.items.append((1, foot[2], body, fill, None, 0.0))
        hr = ph * 0.075
        hy = h2[1] + hr
        head = [(f2[0] + hr * math.cos(2 * math.pi * k / 10),
                 hy + hr * math.sin(2 * math.pi * k / 10)) for k in range(10)]
        scene.items.append((1, foot[2] - 0.01, head, fill, None, 0.0))


