def _hex(c):
    return "#%02x%02x%02x" % (max(0, min(255, int(c[0]))),
                              max(0, min(255, int(c[1]))),
                              max(0, min(255, int(c[2]))))


def _shade(base, n, sundir, alt, gloss=0.0, view=None):
    """Sun, sky and a little bounce. Nothing physical, just consistent."""
    day = max(0.0, min(1.0, (alt + 6.0) / 60.0))
    direct = max(0.0, _dot(n, sundir)) * (0.46 * day)
    skyward = 0.5 + 0.5 * n[2]
    ambient = 0.52 + 0.18 * skyward          # sky and bounce, not a black room
    t = min(1.12, ambient + direct)
    warm = (1.0 + 0.06 * direct, 1.0 + 0.02 * direct, 1.0 - 0.04 * direct)
    c = [base[i] * t * warm[i] for i in range(3)]
    if gloss and view is not None:
        h = _norm(_add(sundir, _mul(view, -1.0)))
        spec = max(0.0, _dot(n, h)) ** 24 * gloss * (0.5 + 0.5 * day)
        c = [c[i] + 255.0 * spec for i in range(3)]
        sky = max(0.0, n[2]) * gloss * 0.28
        c = [c[0] + 90 * sky, c[1] + 118 * sky, c[2] + 150 * sky]
    return _hex(c)


