def _rings(plate):
    return [(plate.outer, False)] + [(h, True) for h in plate.holes]


def _sample(ring, n):
    """n points spaced equally along a ring, so two rings can be matched up."""
    pts = list(ring)
    m = len(pts)
    seg = [math.dist(pts[i], pts[(i + 1) % m]) for i in range(m)]
    total = sum(seg) or 1.0
    out, i, run = [], 0, 0.0
    for k in range(n):
        want = total * k / n
        while run + seg[i] < want and i < m - 1:
            run += seg[i]
            i += 1
        t = 0.0 if seg[i] < 1e-9 else (want - run) / seg[i]
        a, b = pts[i], pts[(i + 1) % m]
        out.append((a[0] + (b[0] - a[0]) * t, a[1] + (b[1] - a[1]) * t))
    return out


def _collar(scene, lower, upper, z, n=64):
    """The horizontal band where one plate steps in or out over another.

    Without it a setback shows the sky through the gap and an overhang has no
    underside. Which it is decides the material: stepping in leaves a terrace,
    stepping out leaves a soffit."""
    a = _sample(lower, n)
    b = _sample(upper, n)
    shrink = abs(G.signed_area(list(upper))) < abs(G.signed_area(list(lower)))
    material = "roof" if shrink else "soffit"
    for k in range(n):
        p0, p1 = a[k], a[(k + 1) % n]
        q0, q1 = b[k], b[(k + 1) % n]
        if (math.dist(p0, q0) < 0.03 and math.dist(p1, q1) < 0.03):
            continue
        quad = [(p0[0], p0[1], z), (p1[0], p1[1], z),
                (q1[0], q1[1], z), (q0[0], q0[1], z)]
        scene.face(quad, material, cull=False)


# Facades the engine can draw, and how much of a storey is window in each.
FACADES = {"glass": ("glass", 1.0), "mirror": ("mirror", 1.0),
           "metal": ("metal", 0.72), "timber": ("timber", 0.55),
           "brick": ("brick", 0.42), "stone": ("stone", 0.42),
           "concrete": ("concrete", 0.42)}


def _facade(project):
    want = (getattr(project.brief, "facade", None) or "glass").strip().lower()
    return FACADES.get(want, FACADES["glass"])


def undercroft(scene, project, keep=None):
    """The open ground plane: what holds the building up, and its soffit.

    A lifted building only reads as lifted if you can see under it, so the
    columns are drawn as shafts and the underside is a lit face rather than
    the bottom edge of a wall."""
    m = project.massing
    keep = keep or (lambda p: True)
    for c in list(m.columns) + list(m.cores):
        ring = G.resample(c.region.outer, 1.5)
        n = len(ring)
        mat = "spandrel" if c.kind == "column" else "wall"
        for k in range(n):
            a, b = ring[k], ring[(k + 1) % n]
            mid = ((a[0] + b[0]) / 2.0, (a[1] + b[1]) / 2.0)
            if not keep(mid):
                continue
            scene.face([(a[0], a[1], 0.0), (b[0], b[1], 0.0),
                        (b[0], b[1], m.lift), (a[0], a[1], m.lift)], mat)
    base = m.levels[0].plate
    _face_with_holes(scene, [(x, y, m.lift) for (x, y) in base.outer][::-1],
                     [[(x, y, m.lift) for (x, y) in h][::-1] for h in base.holes],
                     "soffit")


def building(scene, project, cutaway=None):
    """Facades band by band, so the render shows the windows the schedule
    counts rather than a blank extrusion."""
    m = project.massing
    t = project.brief.wall_t
    top = m.height
    lift = getattr(m, "lift", 0.0)

    def keep(p):
        return cutaway is None or not cutaway(p)

    if lift:
        undercroft(scene, project, keep)

    for i, lv in enumerate(m.levels):
        nxt = m.levels[i + 1].ffl if i + 1 < len(m.levels) else top
        z_sill = lv.ffl + OP.SILL
        z_head = nxt - OP.HEAD_GAP
        base = lv.ffl - OP.HEAD_GAP if i else (lv.ffl if lift else 0.0)
        if i:
            prev = m.levels[i - 1].plate
            _collar(scene, prev.outer, lv.plate.outer, base)
            for k in range(min(len(prev.holes), len(lv.plate.holes))):
                _collar(scene, prev.holes[k], lv.plate.holes[k], base)
        # An opaque facade is mostly solid with a strip of window in it; a
        # glass one is a curtain wall. The brief decides which, so the word
        # "monolithic" changes the picture rather than decorating it.
        solid, band = _facade(project)
        # The facade runs between the plate at this floor and the plate at the
        # next, so a plan that turns or grows gets a ruled surface rather than
        # a vertical extrusion with slots between the floors.
        span = max(1e-6, nxt - lv.ffl)
        for (lower, upper, is_hole) in m.wall_strips(i):
            n = len(lower)
            for k in range(n):
                a0, b0 = lower[k], lower[(k + 1) % n]
                a1, b1 = upper[k], upper[(k + 1) % n]
                mid = ((a0[0] + b0[0]) / 2.0, (a0[1] + b0[1]) / 2.0)
                if not keep(mid):
                    continue
                lo = z_sill + (z_head - z_sill) * (1.0 - band) / 2.0
                hi = z_head - (z_head - z_sill) * (1.0 - band) / 2.0

                def at(p_lo, p_hi, z):
                    t = min(1.0, max(0.0, (z - lv.ffl) / span))
                    return (p_lo[0] + (p_hi[0] - p_lo[0]) * t,
                            p_lo[1] + (p_hi[1] - p_lo[1]) * t, z)

                def strip(z_a, z_b, material):
                    scene.face([at(a0, a1, z_a), at(b0, b1, z_a),
                                at(b0, b1, z_b), at(a0, a1, z_b)], material)

                if lo > base + 0.05:
                    strip(base, lo, solid if solid != "glass"
                          else ("wall" if i == 0 else "spandrel"))
                if hi > lo + 0.05:
                    strip(lo, hi, "glass")
                if z_head > hi + 0.05:
                    strip(hi, z_head,
                          solid if solid != "glass" else "spandrel")
        if i and cutaway is not None:
            _slab(scene, project, i, lv, keep)

    last = m.levels[-1].plate
    _face_with_holes(scene, [(x, y, top) for (x, y) in last.outer],
                     [[(x, y, top) for (x, y) in h] for h in last.holes], "roof")
    par = top + 0.81
    for ring, is_hole in _rings(last):
        pts = G.resample(ring, 3.0)
        n = len(pts)
        for k in range(n):
            a, b = pts[k], pts[(k + 1) % n]
            if not keep(((a[0] + b[0]) / 2.0, (a[1] + b[1]) / 2.0)):
                continue
            scene.face([(a[0], a[1], top - OP.HEAD_GAP),
                        (b[0], b[1], top - OP.HEAD_GAP),
                        (b[0], b[1], par), (a[0], a[1], par)], "parapet")
    _face_with_holes(scene, [(x, y, par) for (x, y) in last.outer],
                     [[(x, y, par) for (x, y) in h] for h in last.holes],
                     "parapet")


def _rgb(hex_str):
    h = (hex_str or "#dddddd").lstrip("#")
    if len(h) != 6:
        return (221, 221, 221)
    return tuple(int(h[i:i + 2], 16) for i in (0, 2, 4))


def _slab(scene, project, i, lv, keep):
    """A cut floor plate.

    The reason to open a building up is to see the plan, so the exposed plate
    is drawn as its rooms in the colours the floor plans use, not as a blank
    tray."""
    for ring, is_hole in _rings(lv.plate):
        pts = G.resample(ring, 3.0)
        n = len(pts)
        for k in range(n):
            a, b = pts[k], pts[(k + 1) % n]
            if keep(((a[0] + b[0]) / 2.0, (a[1] + b[1]) / 2.0)):
                continue
            scene.face([(a[0], a[1], lv.ffl), (b[0], b[1], lv.ffl),
                        (b[0], b[1], lv.ffl - 0.35), (a[0], a[1], lv.ffl - 0.35)],
                       "slab", cull=False)
    _face_with_holes(scene, [(x, y, lv.ffl) for (x, y) in lv.plate.outer],
                     [[(x, y, lv.ffl) for (x, y) in h] for h in lv.plate.holes],
                     "slab")
    fps = getattr(project, "floorplans", None)
    if not fps or i >= len(fps):
        return
    for room in fps[i].rooms:
        base = _rgb(getattr(room, "fill", None))
        if scene.style in ("clay", "white"):
            base = STYLES[scene.style]
        # plan colours are already chosen to be legible; shading them into
        # daylight just washes them out, so they are only knocked back
        fill = ("#ffffff" if scene.style == "line"
                else _hex([c * 0.92 for c in base]))
        scene.face([(x, y, lv.ffl + 0.02) for (x, y) in room.ring], "slab",
                   cull=False, flat=fill,
                   stroke="#9aa0a6" if scene.style != "line" else "#20242a",
                   w=0.35)


