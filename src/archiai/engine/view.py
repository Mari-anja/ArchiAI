def sun(latitude=51.5, day=172, hour=14.0):
    """Where the sun is, so a shadow means something.

    Day is the day of the year; hour is local solar time. Returns the unit
    vector pointing at the sun, its altitude and its azimuth from north."""
    dec = math.radians(23.45 * math.sin(math.radians(360.0 * (284 + day) / 365.0)))
    lat = math.radians(latitude)
    H = math.radians(15.0 * (hour - 12.0))
    alt = math.asin(math.sin(lat) * math.sin(dec)
                    + math.cos(lat) * math.cos(dec) * math.cos(H))
    az = math.atan2(-math.cos(dec) * math.sin(H),
                    math.sin(dec) * math.cos(lat)
                    - math.cos(dec) * math.sin(lat) * math.cos(H))
    v = (math.cos(alt) * math.sin(az), math.cos(alt) * math.cos(az),
         math.sin(alt))
    return _norm(v), math.degrees(alt), math.degrees(az) % 360.0


