def shadow_quads(project, sundir, alt):
    """The building's outline dropped onto the ground along the sun.

    Kept separate from the drawing so the geometry can be checked on its own:
    a shadow that falls the wrong way is a bug you want a test to catch, not
    something to squint at in a picture."""
    if alt < 4.0 or sundir[2] < 0.07:
        return []
    m = project.massing

    def drop(p):
        k = p[2] / sundir[2]
        return (p[0] - sundir[0] * k, p[1] - sundir[1] * k, 0.004)

    quads = []
    for i, lv in enumerate(m.levels):
        nxt = m.levels[i + 1].ffl if i + 1 < len(m.levels) else m.height
        for ring, _h in _rings(lv.plate):
            pts = G.resample(ring, 4.0)
            n = len(pts)
            for k in range(n):
                a, b = pts[k], pts[(k + 1) % n]
                quads.append([(a[0], a[1], lv.ffl), (b[0], b[1], lv.ffl),
                              (b[0], b[1], nxt), (a[0], a[1], nxt)])
    last = m.levels[-1].plate
    quads.append([(x, y, m.height + 0.81) for (x, y) in G.resample(last.outer, 4.0)])
    return [[drop(p) for p in q] for q in quads]


def shadows(scene, project, sundir, alt):
    for q in shadow_quads(project, sundir, alt):
        scene.flat_face(q, "#8d938a", layer=-2)


