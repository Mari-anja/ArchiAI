NAMED = ("aerial-ne", "aerial-nw", "aerial-se", "aerial-sw", "aerial",
         "eye-north", "eye-south", "eye-east", "eye-west",
         "entrance", "courtyard", "roof", "axo", "worm")

_AZ = {"north": 90.0, "south": 270.0, "east": 0.0, "west": 180.0,
       "ne": 45.0, "nw": 135.0, "se": 315.0, "sw": 225.0}


def _frame_distance(project, az, eye_z, fov, aspect, margin=0.84):
    """How far back to stand so the whole building is in the frame.

    Framing from the model rather than a fixed multiple means the same named
    view works for a two storey pavilion and a forty storey tower."""
    m = project.massing
    reach = _reach(project, az)
    across = max(_reach(project, az + 90.0), _reach(project, az - 90.0))
    vt = math.tan(math.radians(fov) / 2.0) * margin
    ht = vt * aspect
    need_up = (m.height + 1.2 - eye_z) / max(vt, 1e-3)
    need_down = eye_z / max(vt, 1e-3)
    need_side = across / max(ht, 1e-3)
    return reach + max(need_up, need_down, need_side, 6.0)


def camera(project, name="aerial-ne", width=1600, height=1000, fov=48.0,
           azimuth=None, elevation=None, distance=None, eye_height=None):
    """A camera for a named view, sized to the building it is looking at.

    Every named view is derived from the model: the distance comes from how
    big the building is, so the same name frames a kiosk and a tower equally
    well. Any part of it can be overridden."""
    m = project.massing
    plate = m.footprint()
    x0, y0, x1, y1 = plate.bbox()
    cx, cy = (x0 + x1) / 2.0, (y0 + y1) / 2.0
    r = max(max(x1 - x0, y1 - y0) / 2.0, m.height * 0.6, 6.0)
    name = (name or "aerial-ne").lower()

    if name == "roof":
        span = max(x1 - x0, y1 - y0) * 1.25
        return Camera((cx, cy - 0.001, m.height + r * 3.0), (cx, cy, m.height),
                      parallel=True, span=span, width=width, height=height)
    if name == "axo":
        az = math.radians(azimuth if azimuth is not None else 235.0)
        el = math.radians(elevation if elevation is not None else 30.0)
        d = distance or r * 6.0
        eye = (cx + math.cos(az) * math.cos(el) * d,
               cy + math.sin(az) * math.cos(el) * d,
               m.height * 0.4 + math.sin(el) * d)
        span = max(x1 - x0, y1 - y0, m.height * 1.6) * 1.5
        return Camera(eye, (cx, cy, m.height * 0.38), parallel=True, span=span,
                      width=width, height=height)

    if name == "courtyard":
        holes = plate.holes
        if holes:
            # Stand at the bottom of the void and look up it. A void that
            # opens as it rises is only legible from underneath, and the eye
            # has to stay inside the narrowest floor or it ends up in a wall.
            h = max(holes, key=lambda k: abs(G.signed_area(k)))
            hx, hy = G.centroid(h)
            hb = G.Region(h).bbox()
            near = min(hb[2] - hb[0], hb[3] - hb[1])
            a = math.radians(azimuth if azimuth is not None else 225.0)
            back = near * 0.30
            eye = (hx - math.cos(a) * back, hy - math.sin(a) * back,
                   eye_height or 1.62)
            if not G.point_in_ring((eye[0], eye[1]), h):
                eye = (hx, hy, eye_height or 1.62)
            return Camera(eye, (hx + math.cos(a) * back * 0.5,
                                hy + math.sin(a) * back * 0.5,
                                m.height * 1.02),
                          fov=max(fov, 62.0), width=width, height=height)
        name = "entrance"

    def stand_off(az, extra):
        """Far enough out to see the whole thing, and clear of the trees."""
        return _reach(project, az) + _pad(project) * 1.9 + extra

    aspect = float(width) / float(height)

    if name == "entrance":
        az = azimuth if azimuth is not None else project.brief.entrance_azimuth
        ez = eye_height or 1.65
        d = distance or max(stand_off(az, 0.0),
                            _frame_distance(project, az, ez, fov, aspect, 0.78))
        a = math.radians(az)
        eye = (cx + math.cos(a) * d, cy + math.sin(a) * d, ez)
        return Camera(eye, (cx, cy, m.height * 0.42), fov=fov, width=width,
                      height=height)

    if name == "worm":
        az = azimuth if azimuth is not None else 225.0
        d = distance or _reach(project, az) + _pad(project) * 0.5
        a = math.radians(az)
        eye = (cx + math.cos(a) * d, cy + math.sin(a) * d, eye_height or 1.30)
        return Camera(eye, (cx, cy, m.height * 0.95), fov=fov + 14.0,
                      width=width, height=height)

    if name.startswith("eye"):
        key = name.split("-")[-1]
        az = azimuth if azimuth is not None else _AZ.get(key, 270.0)
        ez = eye_height or 1.65
        d = distance or max(stand_off(az, 0.0),
                            _frame_distance(project, az, ez, fov, aspect))
        a = math.radians(az)
        eye = (cx + math.cos(a) * d, cy + math.sin(a) * d, ez)
        return Camera(eye, (cx, cy, m.height * 0.45), fov=fov, width=width,
                      height=height)

    key = name.split("-")[-1] if "-" in name else "ne"
    az = azimuth if azimuth is not None else _AZ.get(key, 45.0)
    el = elevation if elevation is not None else 26.0
    ez = max(m.height * 0.5, math.sin(math.radians(el)) *
             _frame_distance(project, az, m.height * 0.5, fov, aspect, 0.80))
    d = distance or _frame_distance(project, az, ez, fov, aspect, 0.80) \
        + _pad(project)
    a, e = math.radians(az), math.radians(el)
    eye = (cx + math.cos(a) * math.cos(e) * d, cy + math.sin(a) * math.cos(e) * d,
           max(m.height * 0.55, math.sin(e) * d))
    return Camera(eye, (cx, cy, m.height * 0.42), fov=fov, width=width,
                  height=height)


