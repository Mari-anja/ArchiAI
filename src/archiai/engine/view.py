ADDONS = ("ground", "sky", "shadow", "context", "trees", "cars", "people",
          "cutaway")
DEFAULT_ADDONS = ("ground", "sky", "shadow")

SKY = {"day": ("#cfe0ec", "#eef3f5"), "clear": ("#a8c8e2", "#e6eef3"),
       "overcast": ("#d7dade", "#eeeff1"), "evening": ("#e7c9ad", "#f4e6d8"),
       "none": None}


def _sky_svg(cam, kind, ground_line=None):
    pair = SKY.get(kind, SKY["day"])
    if not pair:
        return '<rect width="%.0f" height="%.0f" fill="#ffffff"/>' % (
            cam.width, cam.height)
    return ('<defs><linearGradient id="sky" x1="0" y1="0" x2="0" y2="1">'
            '<stop offset="0" stop-color="%s"/><stop offset="1" stop-color="%s"/>'
            '</linearGradient></defs>'
            '<rect width="%.0f" height="%.0f" fill="url(#sky)"/>'
            % (pair[0], pair[1], cam.width, cam.height))


def render(project, name="aerial-ne", style="material", addons=None,
           width=1600, height=1000, latitude=51.5, day=172, hour=14.0,
           sky="day", fov=48.0, azimuth=None, elevation=None, distance=None,
           eye_height=None, cut_azimuth=45.0):
    """One view of the building, as a self-contained SVG string."""
    if style not in STYLES:
        raise ValueError("style must be one of %s" % ", ".join(sorted(STYLES)))
    if name not in NAMED and azimuth is None:
        raise ValueError("view must be one of %s, or give an azimuth"
                         % ", ".join(NAMED))
    want = set(addons if addons is not None else DEFAULT_ADDONS)
    unknown = want - set(ADDONS)
    if unknown:
        raise ValueError("unknown add-on(s): %s" % ", ".join(sorted(unknown)))

    cam = camera(project, name, width, height, fov, azimuth, elevation,
                 distance, eye_height)
    sundir, alt, sunaz = sun(latitude, day, hour)
    sc = Scene(cam, sundir, alt, style)

    if "ground" in want:
        ground(sc, project)
    if "context" in want:
        context(sc, project)
    if "shadow" in want:
        shadows(sc, project, sundir, alt)

    cut = None
    if "cutaway" in want:
        # a quadrant, not a half: opening ninety degrees shows the plates and
        # still leaves three sides of envelope standing
        cx, cy = G.centroid(project.massing.footprint().outer)
        a1 = math.radians(cut_azimuth - 45.0)
        a2 = math.radians(cut_azimuth + 45.0)
        n1 = (math.cos(a1), math.sin(a1))
        n2 = (math.cos(a2), math.sin(a2))

        def cut(p):
            dx, dy = p[0] - cx, p[1] - cy
            return (dx * n1[0] + dy * n1[1] > 0.0
                    and dx * n2[0] + dy * n2[1] > 0.0)

    building(sc, project, cutaway=cut)

    if "trees" in want:
        trees(sc, project)
    if "cars" in want:
        cars(sc, project)
    if "people" in want:
        people(sc, project)

    body = sc.emit()
    if style in PASSES:
        back = {"depth": "#000000", "normal": "#7f7fff",
                "segment": _hex(SEGMENT_SKY), "line": "#ffffff"}[style]
        head = '<rect width="%.0f" height="%.0f" fill="%s"/>' % (
            cam.width, cam.height, back)
    else:
        head = _sky_svg(cam, sky)
    return ('<svg xmlns="http://www.w3.org/2000/svg" width="%d" height="%d" '
            'viewBox="0 0 %d %d">%s%s</svg>'
            % (int(width), int(height), int(width), int(height), head, body))


def describe(project, name="aerial-ne", latitude=51.5, day=172, hour=14.0):
    """What a view is actually of, for the caller's records."""
    cam = camera(project, name)
    sundir, alt, az = sun(latitude, day, hour)
    return {"view": name,
            "eye_m": [round(c, 2) for c in cam.eye],
            "target_m": [round(c, 2) for c in cam.target],
            "projection": "parallel" if cam.parallel else "perspective",
            "field_of_view_deg": None if cam.parallel else round(cam.fov, 1),
            "sun": {"latitude": latitude, "day_of_year": day, "hour": hour,
                    "altitude_deg": round(alt, 1), "azimuth_deg": round(az, 1)}}
